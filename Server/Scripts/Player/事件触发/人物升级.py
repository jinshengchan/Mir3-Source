mapping_table = {
    MirGender.Male: {MirClass.Warrior: MaleWarriorRewards, MirClass.Wizard: MaleWizardRewards,
                     MirClass.Taoist: MaleTaoistRewards, MirClass.Assassin: MaleAssassinRewards},
    MirGender.Female: {MirClass.Warrior: FemaleWarriorRewards, MirClass.Wizard: FemaleWizardRewards,
                       MirClass.Taoist: FemaleTaoistRewards, MirClass.Assassin: FemaleAssassinRewards}}


def OnLevelUp(args):
    Sender = args[0]

    # 检查推荐系统的奖励
    #Referral.CheckReferral(Sender)

    if Sender.Level in mapping_table[Sender.Gender][Sender.Class]:
        Sender.Connection.ReceiveChat("恭喜{}级达到~ 请确认你的礼物。".format(Sender.Level), MessageType.System)
        return mapping_table[Sender.Gender][Sender.Class][Sender.Level]

    return []

PlayerEvent.add_listener("OnLevelUp",OnLevelUp)


